import JSZip from 'jszip';

export interface ProjectFile {
  name: string;
  content: string;
  language?: string;
}

/**
 * Automatically detects or splits code into project files.
 * If the code is an HTML page that includes <style> and <script>, it can split them
 * into a modular folder structure:
 * - index.html
 * - css/style.css
 * - js/script.js
 * - README.md
 */
export function extractProjectFiles(code: string, language: string, projectName: string = 'study-project'): ProjectFile[] {
  const lang = (language || '').toLowerCase().trim();
  const files: ProjectFile[] = [];

  const isHtml = lang === 'html' || lang === 'htm' || code.includes('<!DOCTYPE') || code.includes('<html');

  if (isHtml) {
    let htmlContent = code;
    let extractedCss = '';
    let extractedJs = '';

    // Check for <style> tags
    const styleMatches = htmlContent.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
    if (styleMatches && styleMatches[1].trim().length > 30) {
      extractedCss = styleMatches[1].trim();
    }

    // Check for <script> tags (inline scripts)
    const scriptMatches = htmlContent.match(/<script(?![^>]*src)[^>]*>([\s\S]*?)<\/script>/i);
    if (scriptMatches && scriptMatches[1].trim().length > 30) {
      extractedJs = scriptMatches[1].trim();
    }

    // Add main HTML file
    files.push({
      name: 'index.html',
      content: htmlContent,
      language: 'html'
    });

    // If there is significant CSS, also provide it as a standalone stylesheet
    if (extractedCss) {
      files.push({
        name: 'css/style.css',
        content: `/* Generated by StudyNaija AI Website Studio */\n\n${extractedCss}`,
        language: 'css'
      });
    }

    // If there is significant JS, also provide it as a standalone script
    if (extractedJs) {
      files.push({
        name: 'js/script.js',
        content: `// Generated by StudyNaija AI Website Studio\n\n${extractedJs}`,
        language: 'javascript'
      });
    }

    // Add a README.md
    files.push({
      name: 'README.md',
      content: `# ${projectName.replace(/[-_]/g, ' ').toUpperCase()}\n\nGenerated with 🇳🇬 **StudyNaija AI Website Studio**.\n\n## 🚀 How to Run\n1. Double-click \`index.html\` to open your website directly in any web browser (Chrome, Edge, Safari, Firefox).\n2. To customize the code, open this folder in **VS Code**, **Sublime Text**, or any code editor.\n\n## 📂 Folder Structure\n\`\`\`\n${projectName}/\n├── index.html       (Main webpage structure)\n${extractedCss ? '├── css/style.css    (Website styles and responsive layout)\n' : ''}${extractedJs ? '├── js/script.js     (Interactive functionality and logic)\n' : ''}└── README.md        (Project documentation)\n\`\`\`\n\nHappy Coding with StudyNaija! ⚡`
    });

    return files;
  }

  // Python projects
  if (lang === 'python' || lang === 'py') {
    files.push({
      name: 'main.py',
      content: code,
      language: 'python'
    });

    // Infer basic requirements
    const reqs: string[] = [];
    if (code.includes('import requests')) reqs.push('requests>=2.31.0');
    if (code.includes('import flask') || code.includes('from flask')) reqs.push('Flask>=3.0.0');
    if (code.includes('import numpy')) reqs.push('numpy>=1.26.0');
    if (code.includes('import pandas')) reqs.push('pandas>=2.2.0');
    if (code.includes('import pygame')) reqs.push('pygame>=2.5.0');

    files.push({
      name: 'requirements.txt',
      content: reqs.length > 0 ? reqs.join('\n') : '# No external pip dependencies required\n',
      language: 'text'
    });

    files.push({
      name: 'README.md',
      content: `# ${projectName.replace(/[-_]/g, ' ').toUpperCase()}\n\nPython project created with StudyNaija AI.\n\n## 🚀 Execution\n\`\`\`bash\npython main.py\n\`\`\`\n`
    });

    return files;
  }

  // JavaScript / TypeScript / Node.js
  if (lang === 'javascript' || lang === 'js' || lang === 'typescript' || lang === 'ts') {
    const ext = lang.includes('ts') ? 'ts' : 'js';
    files.push({
      name: `app.${ext}`,
      content: code,
      language: lang
    });

    files.push({
      name: 'package.json',
      content: JSON.stringify(
        {
          name: projectName.toLowerCase().replace(/[^a-z0-9-]/g, '-'),
          version: '1.0.0',
          description: 'Project generated by StudyNaija AI',
          main: `app.${ext}`,
          scripts: {
            start: `node app.${ext}`
          },
          dependencies: {}
        },
        null,
        2
      ),
      language: 'json'
    });

    files.push({
      name: 'README.md',
      content: `# ${projectName.replace(/[-_]/g, ' ').toUpperCase()}\n\nRun with Node.js:\n\`\`\`bash\nnode app.${ext}\n\`\`\`\n`
    });

    return files;
  }

  // SQL projects
  if (lang === 'sql') {
    files.push({
      name: 'schema_and_queries.sql',
      content: code,
      language: 'sql'
    });
    files.push({
      name: 'README.md',
      content: `# Database Project\n\nRun this script in MySQL, PostgreSQL, or SQLite workbench.\n`
    });
    return files;
  }

  // Default fallback
  files.push({
    name: `code.${lang || 'txt'}`,
    content: code,
    language: lang
  });

  return files;
}

/**
 * Packages project files into a .ZIP archive and triggers download.
 */
export async function downloadProjectAsZip(
  files: ProjectFile[], 
  folderName: string = 'studynaija-project'
): Promise<void> {
  const zip = new JSZip();
  const root = zip.folder(folderName) || zip;

  for (const file of files) {
    root.file(file.name, file.content);
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${folderName}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Downloads a single file directly.
 */
export function downloadSingleFile(filename: string, content: string, mimeType: string = 'text/plain'): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
